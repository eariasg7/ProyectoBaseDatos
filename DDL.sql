--CREACION DE LAS TABLAS PARA LA ADMINISTRACION DE LAS REPARACIONES
CREATE TABLE Usuarios (
    UsuarioID BIGINT IDENTITY(1,1),
    Nombre NVARCHAR(250) NOT NULL,
    CorreoElectronico NVARCHAR(50) NOT NULL UNIQUE,
    Telefono INT NOT NULL,
    --
    CONSTRAINT PK_USUARIO PRIMARY KEY (UsuarioID)
);

CREATE TABLE Equipos (
    EquipoId BIGINT IDENTITY(1,1),
    TipoEquipo NVARCHAR(100) NOT NULL,
    Modelo NVARCHAR(200) NOT NULL,
    UsuarioID BIGINT NOT NULL,

    CONSTRAINT PK_EQUIPOS PRIMARY KEY (EquipoId),
    CONSTRAINT FK_USUARIO_EQUIPO FOREIGN KEY (UsuarioID) REFERENCES Usuarios
);

CREATE TABLE Reparaciones (
    ReparacionID BIGINT IDENTITY(1,1),
    EquipoID BIGINT NOT NULL,
    FechaSolicitud DATETIME2 NOT NULL,
    Estado NVARCHAR(20) NOT NULL,

    CONSTRAINT PK_REPARACIONES PRIMARY KEY (ReparacionID),
    CONSTRAINT FK_REPARACION_EQUIPO FOREIGN KEY (EquipoID) REFERENCES Equipos
);

CREATE TABLE Tecnicos (
    TecnicoID BIGINT IDENTITY(1,1),
    Nombre NVARCHAR(500) NOT NULL,
    Especialidad NVARCHAR(500) NOT NULL,

    CONSTRAINT PK_TECNICO PRIMARY KEY (TecnicoID)
);

CREATE TABLE Asignaciones (
    AsignacionID BIGINT IDENTITY(1,1),
    ReparacionID BIGINT NOT NULL,
    TecnicoID BIGINT NOT NULL,
    FechaAsignacion DATETIME2 NOT NULL,

    CONSTRAINT PK_ASIGNACION PRIMARY KEY (AsignacionID),
    CONSTRAINT FK_ASIGNACION_REPARACION FOREIGN KEY (ReparacionID) REFERENCES Reparaciones,
    CONSTRAINT FK_ASIGNACION_TECNICO FOREIGN KEY (TecnicoID) REFERENCES Tecnicos
);

CREATE TABLE DetalleReparacion (
    DetalleID BIGINT IDENTITY(1,1),
    ReparacionID BIGINT NOT NULL,
    Descripcion NVARCHAR(2000) NOT NULL,
    FechaInicio DATETIME2 NOT NULL,
    FechaFin DATETIME2,

    CONSTRAINT PK_DETALLE PRIMARY KEY (DetalleID),
    CONSTRAINT FK_DETALLE_REPARACION FOREIGN KEY (ReparacionID) REFERENCES Reparaciones
);